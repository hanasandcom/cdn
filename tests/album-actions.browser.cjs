// Run against isolated staging only: CDN_ALBUM_BROWSER_TEST=1 CDN_ALBUM_TEST_URL=http://127.0.0.1:18511 node tests/album-actions.browser.cjs
const { chromium, expect } = require('@playwright/test')
const assert = require('node:assert/strict')
const base = process.env.CDN_ALBUM_TEST_URL
assert.equal(process.env.CDN_ALBUM_BROWSER_TEST, '1')
assert.ok(/^http:\/\/127\.0\.0\.1:18\d{3}$/.test(base || ''), 'Use an isolated loopback staging port')
;(async () => {
    const browser = await chromium.launch({ headless: true })
    const context = await browser.newContext({ viewport: { width: 1440, height: 950 } })
    const errors = []
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    async function login(user) {
        await context.addCookies(['id', 'access_token'].map(name => ({ name,
            value: name === 'id' ? user : 'synthetic-token', url: base })))
    }
    async function api(path, method = 'GET', data) {
        const response = await context.request.fetch(base + '/api' + path, {
            method, data, headers: { Origin: base },
        })
        assert.ok(response.ok(), `${method} ${path}: ${response.status()} ${await response.text()}`)
        return response.status() === 204 ? null : response.json()
    }
    const menu = page.getByRole('menu')
    const dialog = page.locator('#album-form')
    const action = name => page.getByRole('button', { name: `Actions for ${name}`, exact: true })
    const row = id => page.locator(`[data-album-id="${id}"]`)
    const openActions = async name => {
        await page.locator('.album-row').filter({ has: page.locator('.album-nav', { hasText: name }) }).hover()
        await action(name).click()
    }
    try {
        await login('owner-test')
        const a = await api('/albums', 'POST', { name: 'Active album' })
        const b = await api('/albums', 'POST', { name: 'Other album' })
        await page.goto(base + '/gallery')
        await page.getByRole('button', { name: 'Active album', exact: true }).click()
        await expect(page.locator('#view-title')).toHaveText('Active album')
        await expect(row(b.id).locator('.library-nav-label')).toHaveCSS('font-weight', '400')
        await expect(row(b.id).locator('.library-nav-label')).toHaveCSS('font-size', '13.12px')
        await row(b.id).click({ button: 'right' })
        await expect(menu).toBeVisible()
        await expect(menu.getByRole('menuitem')).toHaveCount(5)
        await page.keyboard.press('End')
        await expect(menu.getByRole('menuitem', { name: 'Delete album…' })).toBeFocused()
        await page.keyboard.press('Home')
        await expect(menu.getByRole('menuitem', { name: 'Open album' })).toBeFocused()
        await page.keyboard.press('Escape')
        await expect(action('Other album')).toBeFocused()
        await page.keyboard.press('Enter')
        await menu.getByRole('menuitem', { name: 'Rename…' }).click()
        await expect(dialog).toContainText('Other album')
        await dialog.getByLabel('Album name').fill('Renamed album')
        await dialog.getByRole('button', { name: 'Save', exact: true }).click()
        await expect(action('Renamed album')).toBeFocused()
        await expect(page.locator('#view-title')).toHaveText('Active album')
        await openActions('Renamed album')
        await menu.getByRole('menuitem', { name: 'Pin album', exact: true }).click()
        await expect(page.locator('#album-status')).toContainText('pinned')
        await page.reload()
        await expect(page.locator('#owned-albums .album-row').first()).toHaveAttribute('data-album-id', b.id)
        await expect(row(b.id).locator('.album-nav')).toHaveAttribute('aria-label', 'Renamed album, pinned')
        await openActions('Renamed album')
        await menu.getByRole('menuitem', { name: 'Share…' }).click()
        await dialog.getByLabel('Hanasand account ID').fill('viewer-test')
        await dialog.getByLabel('Allow anyone with a link to view').check()
        await dialog.getByRole('button', { name: 'Save sharing' }).click()
        await expect(dialog).toContainText('Sharing settings saved.')
        await expect(dialog).toContainText('viewer-test · Can view')
        const publicLink = await dialog.getByLabel('Public link', { exact: true }).inputValue()
        assert.ok(publicLink.startsWith(base + '/shared/'))
        await page.keyboard.press('Escape')
        await expect(action('Renamed album')).toBeFocused()
        await openActions('Renamed album')
        await menu.getByRole('menuitem', { name: 'Share…' }).click()
        await expect(dialog.getByLabel('Public link', { exact: true })).toHaveValue(publicLink)
        await page.keyboard.press('Escape')
        await login('viewer-test')
        await page.reload()
        await openActions('Renamed album')
        await expect(menu.getByRole('menuitem')).toHaveText(['Open album', 'Pin album'])
        await menu.getByRole('menuitem', { name: 'Pin album', exact: true }).click()
        await page.reload()
        await expect(row(b.id).locator('.album-nav')).toHaveAttribute('aria-label', 'Renamed album, pinned')
        await login('owner-test')
        await page.reload()
        await openActions('Renamed album')
        await menu.getByRole('menuitem', { name: 'Share…' }).click()
        await dialog.getByRole('button', { name: 'Remove access for viewer-test' }).click()
        await expect(dialog.getByLabel('Hanasand account ID')).toBeFocused()
        await dialog.getByLabel('Allow anyone with a link to view').uncheck()
        await dialog.getByRole('button', { name: 'Save sharing' }).click()
        await expect(dialog.getByLabel('Public link', { exact: true })).toBeHidden()
        await page.keyboard.press('Escape')
        await page.route('**/api/albums/*/pin', route => route.fulfill({ status: 503,
            contentType: 'application/json', body: JSON.stringify({ error: 'Test action unavailable' }) }))
        await openActions('Renamed album')
        await menu.getByRole('menuitem', { name: 'Unpin album' }).click()
        await expect(page.locator('#album-status')).toContainText('Test action unavailable')
        await expect(action('Active album')).toBeVisible()
        await page.unroute('**/api/albums/*/pin')
        await page.setViewportSize({ width: 1440, height: 220 })
        await openActions('Renamed album')
        await page.keyboard.press('End')
        await expect(menu).toBeVisible()
        await expect(menu.getByRole('menuitem', { name: 'Delete album…' })).toBeFocused()
        await page.keyboard.press('Escape')
        await page.setViewportSize({ width: 390, height: 844 })
        await page.getByRole('button', { name: 'Browse library', exact: true }).click()
        await openActions('Renamed album')
        await expect(menu).toBeVisible()
        const bounds = await menu.boundingBox()
        assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390)
        await menu.getByRole('menuitem', { name: 'Rename…' }).click()
        await page.keyboard.press('Escape')
        await expect(action('Renamed album')).toBeFocused()
        await expect(page.locator('#photo-library-sidebar')).toHaveClass(/is-open/)
        await page.screenshot({ path: process.env.CDN_ALBUM_SCREENSHOT || '/tmp/cdn-album-menu-mobile.png', fullPage: true })
        await page.setViewportSize({ width: 1440, height: 950 })
        await page.reload()
        await page.getByRole('button', { name: 'Active album', exact: true }).click()
        await openActions('Renamed album')
        await menu.getByRole('menuitem', { name: 'Delete album…' }).click()
        await expect(dialog).toContainText('Renamed album')
        await expect(dialog).toContainText('photos will stay')
        await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeFocused()
        await dialog.getByRole('button', { name: 'Cancel' }).click()
        assert.ok((await api('/albums')).some(album => album.id === b.id))
        await openActions('Renamed album')
        await menu.getByRole('menuitem', { name: 'Delete album…' }).click()
        await dialog.getByRole('button', { name: 'Delete album', exact: true }).click()
        await expect(row(b.id)).toHaveCount(0)
        await expect(page.locator('#view-title')).toHaveText('Active album')
        assert.ok(!(await api('/albums')).some(album => album.id === b.id))
        await row(a.id).locator('.album-nav').focus()
        await page.keyboard.press('Shift+F10')
        await menu.getByRole('menuitem', { name: 'Delete album…' }).click()
        await dialog.getByRole('button', { name: 'Delete album', exact: true }).click()
        await expect(page.locator('#view-title')).toHaveText('Library')
        await expect(page.locator('#create-album')).toBeFocused()
        assert.deepEqual(errors, [])
        console.log('PASS: real staged API browser flow: context targeting, rename, personal pins/reload, sharing/revocation, viewer permissions, keyboard, errors, short viewport, mobile, deletion confirmation')
    } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
